-- 【2026-10-19 如如】日积月累加"词头"列 —— 主附积累的落库依据
--
-- 出处：空空 2026-10-18 的原话
--   "对某种题型……可能一条积累不够，那就两条积累、三条积累……
--    就像错题本里一样，有一个主积累，还有一些附积累跟着。"
--
-- ── 为什么要落库，而不是每次从正文里现算 ──────────────────────────
--   现算当然也能算（`extractHeadword` 是纯函数），但列表要回答一个必须准的问题：
--   **"这个词她一共记过几次"**。前端只拿得到**当前页**（一次 50 条，游标翻页），
--   跨页的同年词条数不到 ⇒ 徽章会显示"2/3"，其实全库有 5 条。
--   数字不准会直接摧毁"主附积累"这件事的可信度 —— 她就不会再信这行字。
--   ⇒ 落一列 + 联合索引，一条 `groupBy` 就能把整页所有词头的总数一次问清。
--
-- ── 为什么存归一化后的值 ──────────────────────────────────────────
--   `headwordKey()` 去掉 emoji / 标点 / 空白 / 大小写 ⇒ "中心思想，怎么写" 与
--   "中心思想 怎么写" 在库里是**同一个字符串**，groupBy 才能把它们算成一组。
--   显示用的原话仍从 content 里取（组里最早那条的写法），不进这一列。
--
-- ── 空值 ──────────────────────────────────────────────────────────
--   可空（TEXT 无 NOT NULL）：
--   ① 摘抄 / 一段感受 / 一封信**本来就没有词头**，不逼它起标题；
--   ② 这条列上线前建的老数据也是空 —— 不是 bug，重新保存一次就补上。
--   ⚠️ **不做一次性回填脚本**：解析 md 第一行只能在应用层做，SQL 做不了；
--      而真实积累目前是 0 条，为几条测试数据写个脚本不值当。
--
-- ⚠️ 本迁移**只加列 + 加索引，不碰任何已有表**（迁移历史有既有漂移，别混进来）。

ALTER TABLE "Insight" ADD COLUMN "headword" TEXT;

CREATE INDEX "Insight_userId_headword_idx" ON "Insight"("userId", "headword");
