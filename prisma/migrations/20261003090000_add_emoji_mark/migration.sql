-- 【2026-10-03 需求第 10 条】每份纸一个**随机 emoji 标识**
--
-- 背景（他的原话，大意）：
--   "每次生成深挖纸、复练卷、积累纸的时候，凡是右上角斜着的'印于 yyyy-mm-dd'的**左边**，
--    随机给一个 emoji 符号作为标识。"
--   · 深挖纸只有正面有印刷时间 ⇒ 正面给一个；
--   · 一份复练卷 / 积累纸**每页**都有印刷时间 ⇒ 这一份的所有页**共用同一个**随机 emoji。
--   这个符号**和纸绑定**（像编号二维码一样，是它的一个属性）：不同的纸可以用同一个，
--   但**同一份**纸的符号相对不变。
--
-- 存法（按"这份纸的来源实体"存，重印同一份纸符号就不变）：
--   · 复练卷 / 积累纸 ⇒ 卷的行上（ReviewVolume.emojiMark）—— 整卷所有页共用一个；
--   · 深挖纸（按题打的那种）⇒ 题的行上（ErrorItem.emojiMark）—— 一题一张纸，给一个。
--
-- 两处都加**可空列**，老数据 NULL ⇒ 下次打印/打开时补一个（惰性生成），不写回填脚本。
-- 纯 ADD COLUMN，不重建表、不动既有数据。
ALTER TABLE "ReviewVolume" ADD COLUMN "emojiMark" TEXT;
ALTER TABLE "ErrorItem" ADD COLUMN "emojiMark" TEXT;
