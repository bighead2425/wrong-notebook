-- 【2026-10-10】题间**从属关系**（主题 / 附题）—— 只加一列 parentId
--
-- 他要的东西：两道题考点一致（甚至只是题干变了变）⇒ 一道当**主题**、其余当**附题**挂上去；
-- 以后"模仿纸"就是照着主题的答案与解析，让孩子去做附题。
--
-- 形状：`parentId` = 这道题的**主题**（null = 它没有主题，即"孤题"或"主题"本身）。
--       "主题有哪些附题"**不存**，用反查得出 —— 一份数据只能有一个真相来源，
--       存两份迟早对不上（这是他担心的"改回未掌握要翻日志才能修复"的真正来源）。
--
-- ⚠️ 与 2026-10-01 那次同一条取舍：日积月累与题的关联也**没走外键**、改存题号。
--    这里存的是 **id 而不是题号**（id 不可变；老题可能没有题号，打印时是 `source || id` 兜底）。
--
-- ⚠️ 为什么是**纯 ADD COLUMN**（不重建表、不落 FOREIGN KEY 约束）：
--    本项目迁移惯例如此（见 20261003180000_add_level_ledger 的注释），
--    SQLite 加外键要重建整张 ErrorItem 表，风险远大于收益。
--    后果只有一条：**硬删**主题时不会自动把附题的 parentId 置空 ——
--    但界面上的删除都走回收箱（soft delete），而"删主题时附题怎么处理"本来
--    就必须由规则显式决定（附题升变 / 连带删除），见 src/lib/item-link.ts。
--    schema.prisma 里仍写着 `onDelete: SetNull`：那是给 Prisma 的语义声明，
--    也是 CI 用 `db push` 建库时的真实约束（CI 的库里是有的）。
--
-- 老数据：全是 NULL = "还没有任何从属关系"，语义正好，不需要回填。
ALTER TABLE "ErrorItem" ADD COLUMN "parentId" TEXT;

-- 反查"这道主题下面挂了哪些附题"要走这个索引（列表/详情页每次都要查）
CREATE INDEX "ErrorItem_parentId_idx" ON "ErrorItem"("parentId");
