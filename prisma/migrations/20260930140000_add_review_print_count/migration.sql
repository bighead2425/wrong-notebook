-- 【2026-09-30】复练纸印刷次数（`ErrorItem.reviewPrintCount`）
--
-- 保守迁移：**只加一列**、带默认值 0 ⇒ 老题读出来就是"没印过复练纸"，零风险。
--
-- 为什么和 printCount 分开放：
--   他要把两个数并排显示 —— "深挖纸打印次数 | 复练纸印刷次数"。
--   两种纸用途不同（深挖=反思怎么错的、复练=练熟），合成一个数就看不出
--   "这题到底是深挖过还是复练过"。分开记，将来做"哪类题该复练"的分析才有依据。
--
-- 记法：印一次复练卷 ⇒ 卷内**所有**题各 +1（题号从卷的快照里找回）。
ALTER TABLE "ErrorItem" ADD COLUMN "reviewPrintCount" INTEGER NOT NULL DEFAULT 0;
