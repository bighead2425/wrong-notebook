-- 【2026-10-15】等级语义改造 v2 —— 加"倒数天数"列 + 建"每日结算"状态表
--
-- 设计原文：docs\14_等级语义改造v2_完整设计_20261015.md（第三节规则、第五节结算）
--
-- ── 这一版要解决什么 ──────────────────────────────────────────────────
--   老等级的毛病：**只看对错、完全不看时间**（`lib/review-status.ts` 的紧迫度只按次数算）
--   ⇒ 一道题放 100 天不练，等级不动。空空 2026-10-15 定：等级 = "这道题有多急着练"，
--   **随时间自动升档**（剩 7 天⇒4 档、剩 1 天⇒5 档）。
--   ⇒ 于是需要一个"还剩几天"的量来驱动等级，并需要一个地方记住"上次结算到哪天"。
--
-- ── 加了什么 ─────────────────────────────────────────────────────────
--   ① `ErrorItem.levelCountdown`（0~49，可空）
--        每次记下复习结果时按"最近的对错"查间隔表写进去；每日结算往下减（夹 0）。
--        等级 = 由它 + 连对次数决定。**落库是为了让数据库能按等级排序/筛选/分页**
--        （现算的话那 15+ 个读点全得改，且筛选分页没法做）。
--        `NULL` = 老数据还没初始化，首次结算时补上。
--   ② `DailySettle`（一个用户一行，userId 就是主键）
--        存 `lastSettledOn`（上次结算到哪天）+ `runningSince`（结算中锁）。
--
-- ── 两个必须写明的取舍 ───────────────────────────────────────────────
--   ⚠️ **幂等靠"减数"，不靠"减 1"**：结算时算 `减数 = 今天 − lastSettledOn`，
--      再用它去减每题的 `levelCountdown`。这样**漏跑 3 天 ⇒ 减数 3 ⇒ 一次补上**；
--      而"每天减 1"漏一天就永久错，且不会自愈。
--   ⚠️ **"上次结算日"必须进库，不能写 config 文件**：它要和"每题的新等级"
--      **在同一个事务里原子提交**。写文件就没法一起提交 ⇒ 断电时出现"等级更新了但
--      日期没写"（或反之）⇒ 下次结算重复扣/漏扣。
--
-- ── 迁移惯例（照本项目的老规矩）───────────────────────────────────────
--   · 只 **ADD COLUMN**（不重建 ErrorItem —— SQLite 重建整张表风险远大于收益）；
--   · 建的是**新表**（DailySettle），所以可以正常落 FOREIGN KEY；
--   · **不动任何既有列、不回填任何老数据**（`levelCountdown` 留 NULL，由首次结算初始化）。
--
-- 老数据会怎样：首次结算时，没有 `levelCountdown` 的题会按"最近的对错"补一个间隔
--   （等价于"假设刚复习完"），等级随之按新规则重算一遍。
--   ⚠️ **这是预期行为**：1-5 的语义从"等级"变成"紧迫度"了，老值的含义已经不存在，
--      不重算反而是错的。上线后等级整体会变一次，之后按新规则演进。

ALTER TABLE "ErrorItem" ADD COLUMN "levelCountdown" INTEGER;

CREATE TABLE "DailySettle" (
    "userId" TEXT NOT NULL PRIMARY KEY,
    "lastSettledOn" TEXT NOT NULL,
    "runningSince" DATETIME,
    "updatedAt" DATETIME NOT NULL,
    CONSTRAINT "DailySettle_userId_fkey" FOREIGN KEY ("userId") REFERENCES "User" ("id") ON DELETE CASCADE ON UPDATE CASCADE
);
