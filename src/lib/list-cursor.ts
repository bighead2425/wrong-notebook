/**
 * 【2026-10-09】列表翻页的**游标**（keyset / "从这一条之后再来一批"）。
 *
 * ── 为什么用游标，而不是"第几页" ──────────────────────────────────────
 * 这两个列表（日积月累、复练卷）是**上拉加载更多**的用法：一边往下翻，一边还在往里加东西。
 * 用"第几页"会出两种错，而且都要等用户撞上才发现：
 *   · **重复**：翻到第 2 页时前面新增了一条，第 1 页的最后一条被挤到第 2 页 ⇒ 看到两遍；
 *   · **漏项**：中间删掉一条，第 2 页的第一条被顶到第 1 页 ⇒ 那条你永远翻不到。
 * "给我这一条**之后**的 50 条"不受新增/删除影响 —— 因为它的锚点是**内容本身**（某某时间），
 * 不是"第几页"这个位置。
 *
 * ── 这个文件只管"拼串/拆串"，不管业务 ──────────────────────────────────
 * 具体拿哪几个字段当锚点由调用方决定（日积月累用 `日期 + 当日序号`，卷用 `id`）。
 * 拆出来单独一个文件，是为了让"分隔符会不会被子串撞上""中文/特殊符号要不要转义"
 * 这类**容易写错、又不容易在界面上发现**的事有单测钉着。
 *
 * ⚠️ 游标是**不透明字符串**：客户端只负责原样带回来，不要去解析、不要自己拼。
 */

/** 把几个值拼成一个游标串（每个值单独转义，所以值里出现分隔符也不怕） */
export function encodeCursor(...parts: (string | number)[]): string {
    return parts.map((p) => encodeURIComponent(String(p))).join("|");
}

/**
 * 把游标串拆回几个值；**数量不对或转义坏了都返回 null**（当作"没有游标"）。
 *
 * 为什么坏值不报错、而是当没有：游标是客户端带来的东西（可能过期、可能被手改），
 * 遇到坏值最合理的处理是**从第一页重新开始**，而不是给用户一个 500。
 */
export function decodeCursor(
    raw: string | null | undefined,
    count: number,
): string[] | null {
    if (!raw) return null;
    if (count < 1) return null;
    const parts = raw.split("|");
    if (parts.length !== count) return null;
    const out: string[] = [];
    for (const p of parts) {
        try {
            out.push(decodeURIComponent(p));
        } catch {
            return null;
        }
    }
    return out;
}
