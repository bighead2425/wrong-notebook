/** 英语知识点体系
 *
 * 【2026-11-01 重构】和语文同理：英语也是**累积型**学科，
 * "一般现在时"从小学考到高考，只是句子越来越长。
 *
 * 原结构的问题（用户指出）：
 *   · 小学「句型与语法」有具体时态，高中只剩一个笼统的「时态与语态」
 *     ⇒ 高中错了一道一般现在时的题，无处可挂，粒度掉一级；
 *   · 初中、高中**完全没有"词汇"这一块**，而词汇恰恰是英语最普遍的薄弱点。
 *
 * 现在：三个学段统一板块（语音 / 词汇 / 语法 / 阅读 / 写作 / 能力），
 * 语法再往下分节（时态 / 语态 / 从句 / 非谓语 / 词法 / 特殊句式），
 * **每节下的考点名在三个学段保持一致**，"一般现在时"三处都能找到。
 *
 * 覆盖性对照：
 *   一般现在时 / 一般过去时 …… 小学✓ 初中✓ 高中✓
 *   名词单复数 / 人称代词 …… 小学✓ 初中✓ 高中✓
 *   词汇（说法/辨析/搭配） …… 小学✓ 初中✓ 高中✓
 *   从句 ……………………………  —   初中✓ 高中✓
 *
 * 关于"词汇"为什么这样分（用户原本想按名词/动词/形容词挂）：
 *   按词性挂只能得出"我错了 12 个动词"，下次复习还是不知道复习哪个。
 *   按「构词法与词形 / 词义辨析 / 固定搭配 / 词性与用法」分，
 *   "词汇弱"才能落到**是哪一类问题**（记不住词形？还是分不清辨析？）。
 *
 * 取数口径见 `lib/ai/tag-scope.ts` 的 SUBJECT_SCOPE —— 这类学科只给**当前学段**。
 */

