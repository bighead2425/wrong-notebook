/**
 * 【custom-v36】裁剪窗工作画布的尺寸上限。
 *
 * ── 起因 ────────────────────────────────────────────────────────────
 * v35 实测：12MP 级手机照片（约 4000×3000）进裁剪窗，点一次「🔄转」，
 * 画面被切成竖向几条、各条内容方向/比例还不一致，橡皮擦也跟着"擦哪儿乱哪儿"。
 *
 * ── 根因（v36 二次审计才查实，上一稿的推测是错的）────────────────────
 * 转置矩阵的数学没错（image-rotation 有单测钉着）。错在**呈现层**：
 * 上一稿认为是"GPU 纹理分块重传不全"，查 Chromium 工单后改判 ——
 * 栅格化预算是按 **元素布局尺寸 × 设备像素比** 算的。旧写法把 canvas 的布局尺寸
 * 设成图片自然像素（4000×3000 CSS px）再用 `scale()` 缩小，DPR 1.25~2 时一次
 * "按原生比例栅格化"要 75~300MB，超过 tile 内存上限，Chromium **栅格化做一半就放弃**
 * （Chromium issue #870222 原话），于是屏幕上出现"新内容 + 旧内容碎片、比例各异"的拼条。
 * 橡皮擦"乱"是同根症状：用户照着屏幕（错画面）下笔，真实画布里并没有那些东西。
 *
 * 真正的修法是**把布局尺寸改成显示尺寸**（不再用 scale 缩放，见组件里 wrap 的长注释）
 * —— 这样栅格化尺寸永远被视口封顶，与分辨率、DPR 都无关，故障路从结构上堵死。
 *
 * ── 那这个上限还管什么 ──────────────────────────────────────────────
 * 只管**内存**：裁剪窗同时活着 5 张画布，而用户的机器空闲内存只有一两百 MB。
 * 3200 时约 150MB，收到 2560 约 100MB。画质不吃亏 —— 下游全链路以 1920 为上限
 * （AI 分析压缩到 1920、扫描出图 MAX_OUTPUT_EDGE=1920），2560 下裁 1/4 版面的题
 * ≈1280px，按 10cm 宽打印约 300dpi。
 *
 * 注意：缩放只影响"裁剪窗里的工作副本"，原始文件不动；「原图」键恢复的
 * firstImageRef 就是从缩放后的基准图克隆的，天然同尺寸，不会出现两套坐标系。
 */

/**
 * 编辑画布长边上限。
 *
 * ── 为什么是 2560（v36 审计后从 3200 收下来）────────────────────────
 * 上一稿定 3200 的理由是"绕开 GPU 单块纹理门槛"，那个理由在 v36 审计后被推翻了：
 * 真正决定渲染是否出错的是 **元素布局尺寸 × 设备像素比**（见组件里 wrap 那段长注释），
 * 而布局尺寸已经改成显示尺寸，与画布内部分辨率无关 —— 所以尺寸上限**不再是渲染问题**，
 * 只剩内存问题，按内存来定：
 *
 *   · 裁剪窗同时活着 5 张画布：base / overlay / orig / work / 首图副本；
 *   · 3200×2400 每张 30MB → 合计约 150MB；2560×1920 每张 19.6MB → 约 100MB。
 *     而用户的机器空闲内存常年只有一两百 MB，这 50MB 的差别是实打实的。
 *
 * 画质不吃亏的依据：下游全链路以 1920 为上限（AI 分析压缩到 1920、扫描出图
 * MAX_OUTPUT_EDGE=1920）；2560 下裁一个 1/4 版面的题目 ≈ 1280px，按 10cm 宽打印
 * 约 300dpi，够用。
 */
export const MAX_EDIT_EDGE = 2560;

/**
 * 等比收缩到长边不超过 maxEdge；本身不超限的图原样返回（**只缩小、不放大**）。
 * 结果向上取整并至少 1px，避免 0 尺寸画布。
 */
export function fitEditSize(
    w: number,
    h: number,
    maxEdge: number = MAX_EDIT_EDGE,
): { w: number; h: number; scaled: boolean } {
    const iw = Number.isFinite(w) ? Math.max(1, Math.round(w)) : 1;
    const ih = Number.isFinite(h) ? Math.max(1, Math.round(h)) : 1;
    const edge = Number.isFinite(maxEdge) && maxEdge >= 1 ? maxEdge : 1;
    const longest = Math.max(iw, ih);
    if (longest <= edge) return { w: iw, h: ih, scaled: false };
    const k = edge / longest;
    return {
        w: Math.max(1, Math.round(iw * k)),
        h: Math.max(1, Math.round(ih * k)),
        scaled: true,
    };
}
