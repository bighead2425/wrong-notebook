/**
 * 纸面上的日期写法 —— **统一 `yyyy-mm-dd`**。
 *
 * 为什么单独一个模块：纸面上出现的日期有好几处（复习日期格、身份条上的打印日），
 * 它们必须**写法一致**；而日期格式化又最容易出「本地时区 vs UTC 差一天」
 * 这种**不报错、只印错**的问题，所以要能被单测钉住。
 *
 * ⚠️ 一律用**本地时间**字段（getFullYear / getMonth / getDate），
 *    不要用 `toISOString()`（它是 UTC，晚上打印会印成前一天）——
 *    这个坑在别的项目上踩过，纸面上的日期错一天没人会立刻发现。
 *
 * ⚠️ 2026-09-24 改定：原先写 `9/25`（月/日、不补零），空空看纸样后说
 *    "看上去不舒服"，且跨年时 `10/1` 分不清哪一年 ⇒ 全项目纸面统一 yyyy-mm-dd。
 */

const pad = (n: number) => String(n).padStart(2, '0');

/** `2026-09-25` —— 纸面唯一格式（复习日期格、身份条打印日都用这个） */
export function formatIsoDate(date: Date): string {
    return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`;
}

/**
 * 【2026-10-14】**日期格**专用：`MM-DD`（如 `10-15`）。
 *
 * ⚠️⚠️ 这一条**推翻了 2026-09-24 的定案**，务必看清来龙去脉：
 *    · 2026-09-24 之前纸面写 `9/25`（月/日、不补零）⇒ 空空看纸样后说"看上去不舒服"，
 *      且跨年 `10/1` 分不清哪一年 ⇒ **全项目纸面统一 `yyyy-mm-dd`**。
 *    · 2026-10-14 加第 4 个日期格后，页脚右区（约 123.5mm）**装不下四组 `2026-10-15`**
 *      （超约 10~15mm）⇒ 空空当天拍板：**日期格改用 `MM-DD`**
 *      （带补零、用连字符，与当年被否的 `9/25` 不完全一样）。
 *      代价（他知情）：**跨年那张看不出年份**。
 *
 * ⇒ 与 `formatIsoDate` 的**分工**：
 *    **日期格**用 `formatMonthDay`（省宽度）；**身份条「印于 …」仍用 `formatIsoDate`**（带年份）。
 *    于是"这是哪一年"在纸面上仍然查得到，只是不在格子里。
 */
export function formatMonthDay(date: Date): string {
    return `${pad(date.getMonth() + 1)}-${pad(date.getDate())}`;
}

/**
 * 【2026-10-14】**日期格那一行最前面那个年份**（如 `2026`）。
 *
 * 为什么需要它：`MM-DD` 把年份丢了，而**日期格在反面**、身份条「印于 …」在**正面**
 * ⇒ 反面那一页上没有任何地方写年份。所以年份要在日期格这行自己带出来，
 * **只带一次**，写在第一个颜色格前面（用第一个格的颜色）。
 *
 * ⚠️⚠️ **"只标第一个年份"是有意取舍，不是漏了**（空空 2026-10-14 拍板 A）：
 *    偏移 `[1,7,21,49]` 天 ⇒ **11 月中旬以后**，后几格其实已经跨到**次年**，
 *    严格说该在"跨年那一格"前面再标一次。但那样要 **2 个年份 token（约 18.6mm）**，
 *    而页脚右区**只剩 11.9mm**（实测见 `docs\11_纸面尺寸账_深挖纸页脚.md`）。
 *
 *    空空的判断（原话）：**"跨年的总量比较小，而且前面的日期大、后面的日期小，
 *    自然就是跨年了，不难理解。"**
 *    ⇒ 接受"年末那几个月（如 12-22 后面跟 01-05）看起来像同一年"这点小误差，
 *      换取**不动任何已定的纸面间距**。
 *    📌 将来真要补：把 `reviewDateSlots` 里 `i === 0` 的条件改成
 *      "与上一格不同年"，并同时让出约 10mm 宽度（见 `docs\11` 的方案 B）。
 */
export function formatYear(date: Date): string {
    return String(date.getFullYear());
}
