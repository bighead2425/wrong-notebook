/**
 * 【custom-v34】批量上传队列里"退出会不会丢东西"的判定。
 *
 * 为什么单独抽成一个纯函数：这条规则被写错过一次，而**写错的表现很反直觉** ——
 * 用户把 2 张照片各裁出一道题、两道都成功入库了，点「结束批量」却弹
 * "还有 2 张没入库"。功能没坏，只是拦错了人，但这种"警报乱响"会直接
 * 摧毁提示的可信度（下次真有东西要丢，用户也会当它是噪声直接点掉）。
 *
 * ── 规则 ─────────────────────────────────────────────
 *
 * 只有"**还没变成任何成品、自己也还没入库**"的图，退出才是真丢。逐类看：
 *
 *   · 已入库（status === "saved"）           → 不丢，本来就在题库里了；
 *   · 预处理图还没入库（processed 且未 saved）→ **会丢**，它是浏览器里刚生成的
 *     新图（裁出来/美化出来的那一道），退出即消失、还找不回来；
 *   · 待处理原图，从没被加工过               → **会丢**，用户可能只是选错了图；
 *   · 待处理原图，已被加工过（treated，界面上是灰的）
 *                                            → 视为**不丢**：它只是"留着以便再拆一道"
 *     的备份，它加工出的成品已经在上面那条里计过数了。真正值钱的是成品，不是原图。
 *
 * 注意 `treated` 在预处理图上也会被置 true（"这张被编辑过"），所以判据必须是
 * `treated && !processed`，光看 treated 会把"编辑过但还没入库的成品"也放过。
 */
export interface QueueItemLike {
    /** 是否已经进入「预处理」区（已被加工成成品） */
    processed: boolean;
    /** 已被编辑器加工过（成品会带这个标记，待处理原图的"备份"状态也带） */
    treated?: boolean;
    /** 队列状态：只有 "saved" 表示已入库 */
    status: string;
}

/** 退出批量页时，真正会被丢掉（且找不回来）的图片张数 */
export function countWillBeLost(items: QueueItemLike[]): number {
    return items.filter((i) => {
        if (i.status === "saved") return false;
        // 已加工过的待处理原图 = 备份，不算
        if (i.treated && !i.processed) return false;
        return true;
    }).length;
}
