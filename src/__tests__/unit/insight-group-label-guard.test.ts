/**
 * 【2026-10-19 真真】看门测试：**组框上那行必须显示"这一组自己的词头"**。
 *
 * ══════════════════════════════════════════════════════════════════════
 * 为什么加这一条（又是一个"纯函数对了、界面没用它"的坑）
 *
 * 如如那棒的纯函数 `buildHeadwordList()` 返回的 `headline` **完全正确**（单测也断言了），
 * 但管理页渲染组框时写的是**字面量** `L('同一个词', 'Same word')` ——
 * 于是屏幕上每一个框都写着"同一个词 · N 条"。
 *
 * 空空 2026-10-19 的截图就是现场：两组明明是两个不同的词
 * （一组「同一个词」、一组「测试12345」），框上却都写"同一个词" ——
 * 一眼看去像"系统把两件事混成一件"，**比不分组更让人犯嘀咕**。
 *
 * ⇒ 纯函数有单测，但"界面有没有用它"没人管。这条就是补那个缺口。
 *
 * ⚠️ 判据故意写得**笨**（扫源码里有没有 `entry.headline` / 有没有写死那句）：
 *    组件渲染没有单测环境，能钉住"这一行没被改回去"就够了。
 *    以后真要重构，改这条测试比让用户再撞一次便宜。
 * ══════════════════════════════════════════════════════════════════════
 */

import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';

const PAGE = 'src/app/insights/page.tsx';

describe('同词头组框的标签', () => {
    it('★ 渲染时必须**真的把 headline 插进 JSX**（注释里提到不算）', () => {
        const src = readFileSync(PAGE, 'utf8');
        /**
         * ⚠️ 判据必须是 `{entry.headline}` 这种 **JSX 插值**形态。
         *    第一版写的是 `toContain('entry.headline')` —— 而解释这段的注释里
         *    正好也有这几个字（反引号包着），于是**改回写死的版本它照样绿**。
         *    这就是"假护栏"，已当场改掉（教训 #23：护栏必须先让它红一次）。
         */
        expect(src).toMatch(/\{entry\.headline\}/);
    });

    it('★ 不许再把「同一个词」当字面量写进组框', () => {
        const src = readFileSync(PAGE, 'utf8');
        // 这个字面量就是当初那个 bug 的原样；允许出现在注释里（解释为什么不能这么写），
        // 所以只禁"代码里调用 L('同一个词'"这种形态
        expect(src).not.toMatch(/L\(\s*'同一个词'/);
        expect(src).not.toMatch(/L\(\s*"同一个词"/);
    });
});
