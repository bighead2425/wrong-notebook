/**
 * 标签路径的单测。
 *
 * 这个模块是为一个真实 bug 写的：详情页原来拿 `tagResolution.section` 拼路径，
 * 而那个字段存的是**章名** ⇒ 几道题都显示成
 * 「五年级上 › 第一单元 小数的再认识和加减法」，看起来像全挂在同一个地方。
 */

import { describe, it, expect } from 'vitest';
import { chainToPaths } from '@/lib/tag-path';

describe('chainToPaths', () => {
    it('四层：册 › 章 › 节 › 点', () => {
        const r = chainToPaths([
            '五年级上', '第一单元 小数的再认识和加减法', '单位换算与复名数', '长度单位换算',
        ]);
        expect(r.path).toBe('五年级上 › 第一单元 小数的再认识和加减法 › 单位换算与复名数 › 长度单位换算');
    });

    /**
     * 词表里确实存在"节名 = 知识点名"（如「小数的大小比较」既是节、
     * 下面又挂了一个同名知识点）。不折叠就会显示成
     * 「… › 小数的大小比较 › 小数的大小比较」。
     */
    it('相邻重名折叠成一段', () => {
        const r = chainToPaths([
            '五年级上', '第一单元 小数的再认识和加减法', '小数的大小比较', '小数的大小比较',
        ]);
        expect(r.path).toBe('五年级上 › 第一单元 小数的再认识和加减法 › 小数的大小比较');
    });

    it('只有一层时原样返回，不能折叠成空串', () => {
        expect(chainToPaths(['五年级上']).path).toBe('五年级上');
    });

    it('空链不炸', () => {
        expect(chainToPaths([]).path).toBe('');
    });

    /**
     * 回归：这是那个 bug 的原始形态。
     * 同属五上第一单元的三道题，路径必须**彼此不同**（各自有各自的节），
     * 而不是全都显示成「五年级上 › 第一单元」。
     */
    it('同一章下的不同节，路径必须不同（这就是那个 bug）', () => {
        const a = chainToPaths(['五年级上', '第一单元 小数的再认识和加减法', '单位换算与复名数', '长度单位换算']);
        const b = chainToPaths(['五年级上', '第一单元 小数的再认识和加减法', '小数加减法', '小数减法']);
        const c = chainToPaths(['五年级上', '第一单元 小数的再认识和加减法', '小数的大小比较']);
        expect(new Set([a.path, b.path, c.path]).size).toBe(3);
    });

    it('英语：学段 › 章 › 节 › 点层层不同，不折叠', () => {
        expect(chainToPaths(['小学', '阅读', '对话', '情景对话']).path)
            .toBe('小学 › 阅读 › 对话 › 情景对话');
    });
});
